const assert=require('node:assert/strict');

module.exports=async function testDashboardComposition(page){
  const total=key=>page.locator(`[data-composition-total="${key}"]`).textContent();
  const matrix=page.locator('#dashboardCompositionMatrix');
  assert.equal(await total('people'),'22');assert.equal(await total('teams'),'3');
  assert.equal(await total('companies'),'2');assert.equal(await total('contracts'),'5');
  assert.match(await page.locator('#dashboardComposition .analytics-scope-note').textContent(),/Ativos a 02\/11\/2026/);
  assert.equal(await page.locator('#dashboardCompositionTeams .analytics-composition-value strong').allTextContents().then(values=>values.reduce((sum,value)=>sum+Number(value),0)),22);
  assert.deepEqual(await page.locator('#dashboardCompositionContracts .analytics-composition-value strong').allTextContents(),['4','4','4','4','3','3']);
  assert.match(await page.locator('#dashboardCompositionContracts').textContent(),/40 horas/);
  assert.match(await page.locator('#dashboardCompositionContracts').textContent(),/Bolsa de Formação/);
  assert.match(await page.locator('#dashboardCompositionContracts').textContent(),/Por preencher/);
  assert.deepEqual(await page.locator('#dashboardCompositionCompanies .analytics-composition-value strong').allTextContents(),['12','5','5']);
  assert.equal(await matrix.locator('tbody tr').count(),4);
  assert.equal(await matrix.locator('[data-composition-team="a"] .composition-total').textContent(),'9');
  assert.equal(await matrix.locator('[data-composition-team="b"] .composition-total').textContent(),'11');
  assert.equal(await matrix.locator('tfoot .composition-total').textContent(),'22');
  await page.locator('[data-composition-view="companies"]').click();
  assert.equal(await page.locator('[data-composition-view="companies"]').getAttribute('aria-pressed'),'true');
  assert.deepEqual(await matrix.locator('tfoot td').allTextContents(),['Total','12','5','5','22']);
  await page.locator('#dashboardAnalyticsTeam').selectOption('a');
  assert.equal(await total('people'),'9');
  assert.equal(await matrix.locator('tbody tr').count(),1);
  assert.equal(await matrix.locator('tfoot .composition-total').textContent(),'9');
  await page.locator('#dashboardAnalyticsFrom').fill('2026-10-01');
  await page.locator('#dashboardAnalyticsFrom').dispatchEvent('change');
  await page.locator('#dashboardAnalyticsTo').fill('2026-10-31');
  await page.locator('#dashboardAnalyticsTo').dispatchEvent('change');
  assert.equal(await total('people'),'9','current composition is independent of movement dates');
  await page.locator('#dashboardAnalyticsTeam').selectOption('*');
  await page.getByRole('button',{name:'Ano',exact:true}).click();
  await page.locator('#dashboardAnalyticsTo').fill('2026-11-02');
  await page.locator('#dashboardAnalyticsTo').dispatchEvent('change');
  await page.locator('[data-composition-view="contracts"]').click();
  assert.equal(await total('people'),'22');
  await page.evaluate(()=>{currentProfile={role:'gestor',person_id:'a'};renderDashboard();});
  assert.equal(await total('people'),'9','manager totals contain only the current authorized team');
  assert.equal(await matrix.locator('tbody tr').count(),1);
  assert.equal(await matrix.locator('tbody tr').getAttribute('data-composition-team'),'a');
  await page.evaluate(()=>{currentProfile={role:'admin',display_name:'Teste'};renderDashboard();});
  assert.equal(await total('people'),'22');
  assert.equal(await page.evaluate(()=>JSON.stringify(state)===window.originalState),true);
  console.log(JSON.stringify({currentPeople:22,teamCounts:true,contractCounts:true,companyCounts:true,crossTotals:true,missingFieldsVisible:true,caseNormalization:true,datedTeamAssignment:true,movementDatesIndependent:true,readOnly:true}));
};
