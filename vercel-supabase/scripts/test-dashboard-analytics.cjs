const assert=require('node:assert/strict');
const path=require('node:path');
const testDashboardComposition=require('./test-dashboard-composition.cjs');
const testDashboardExitReasons=require('./test-dashboard-exit-reasons.cjs');

module.exports=async function testDashboardAnalytics(page,output){
  await page.reload();await page.locator('#dashboardAnalytics').waitFor();
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>setThemePreference('light'));
  await page.evaluate(()=>window.scrollTo(0,0));
  const metric=key=>page.locator(`[data-analytics-total="${key}"]`).textContent();
  assert.equal(await metric('entries'),'19');assert.equal(await metric('exits'),'9');assert.equal(await metric('balance'),'+10');
  assert.equal(await page.locator('.analytics-kpis dd').count(),3);
  assert.equal(await page.locator('#dashboardCommissionModels').count(),0);
  assert.doesNotMatch(await page.locator('#dashboardAnalytics').textContent(),/comiss|transfer|efetivo|taxa de saída/i);
  assert.equal(await page.locator('.analytics-month').count(),11,'future months are not invented');
  assert.ok(await page.locator('.analytics-kpis dd').first().evaluate(el=>parseFloat(getComputedStyle(el).fontSize))>=44);
  assert.ok((await page.locator('#dashAnnualMovements').boundingBox()).height>=300);
  assert.ok(await page.locator('.analytics-month-column .dash-movement-bar').evaluateAll(bars=>Math.max(...bars.map(bar=>bar.getBoundingClientRect().height)))>=180);
  assert.ok(await page.locator('#dashboardTeamAnalysis .analytics-table').evaluate(el=>parseFloat(getComputedStyle(el).fontSize))>=16);
  assert.equal(await page.locator('#dashboardTeamAnalysis tbody img').count(),3);
  await testDashboardComposition(page);
  await testDashboardExitReasons(page);
  await page.locator('#dashboardExitReasons').screenshot({path:path.join(output,'dashboard-exit-reasons-desktop.png'),style:'body > header { opacity:0; }'});
  await page.locator('#dashboardComposition').screenshot({path:path.join(output,'dashboard-composition-desktop.png'),style:'body > header { opacity:0; }'});
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:path.join(output,'dashboard-analytics-desktop.png'),fullPage:true});
  await page.locator('#dashboardAnalyticsFrom').fill('2026-11-01');await page.locator('#dashboardAnalyticsFrom').dispatchEvent('change');
  await page.locator('#dashboardAnalyticsTeam').selectOption('a');
  assert.equal(await metric('entries'),'0');assert.equal(await metric('exits'),'0');assert.equal(await metric('balance'),'0');
  const teamRow=page.locator('[data-analytics-team="a"]');
  assert.equal(await teamRow.locator('td').last().textContent(),'0','a team transfer must not change the admissions balance');
  await page.getByRole('button',{name:'Ano',exact:true}).click();
  await page.locator('[data-analytics-team="a"] td').nth(1).getByRole('button').click();
  assert.equal(await page.locator('#dashboardMovementDetails').getAttribute('open'),'');
  assert.equal(await page.locator('#dashboardMovementDetails tbody tr').count(),9);
  assert.match(await page.locator('#dashboardMovementDetails tbody').textContent(),/Colaborador 0/,'a hire remains with the original team after a transfer');
  assert.equal(await page.locator('#dashboardAnalyticsEventType option[value="transfer"]').count(),0);
  await page.locator('#dashboardAnalyticsEventType').selectOption('exit');
  assert.equal(await page.locator('#dashboardMovementDetails tbody tr').count(),0);
  await page.locator('#dashboardAnalyticsTeam').selectOption('*');
  await page.locator('#dashboardAnalyticsEventType').selectOption('all');
  assert.equal(await page.locator('#dashboardMovementDetails tbody tr').count(),28,'only admissions and departures are listed');
  await page.locator('#dashboardMovementDetails summary').click();
  for(const width of [820,390,320]){
    await page.setViewportSize({width,height:900});
    await page.evaluate(()=>window.scrollTo(0,0));
    for(const selector of ['#dashboardAnalytics','#dashboardTeamAnalysis','#dashboardTeamChart','#dashAnnualMovements','#dashboardComposition','#dashboardCompositionMatrix','#dashboardExitReasons']){
      const box=await page.locator(selector).boundingBox();
      assert.ok(box.x>=0 && box.x+box.width<=width+1,selector+' fits '+width);
      assert.equal(await page.locator(selector).evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,selector+' has no content overflow');
    }
    assert.equal(await page.locator('.analytics-kpis>div').evaluateAll(items=>items.every(item=>item.scrollWidth<=item.clientWidth+1)),true);
    assert.ok(await page.locator('.analytics-kpis dd').first().evaluate(el=>parseFloat(getComputedStyle(el).fontSize))>=36);
    assert.equal(await page.locator('.analytics-composition-label').evaluateAll(items=>items.every(item=>item.scrollWidth<=item.clientWidth+1)),true);
    await page.locator('[data-composition-view="companies"]').click();
    assert.equal(await page.locator('#dashboardCompositionMatrix').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true);
    await page.locator('#dashboardComposition').screenshot({path:path.join(output,`dashboard-composition-${width}.png`),style:'body > header { opacity:0; }'});
    await page.locator('[data-composition-view="contracts"]').click();
    await page.locator('#dashboardExitReasons').screenshot({path:path.join(output,`dashboard-exit-reasons-${width}.png`),style:'body > header { opacity:0; }'});
    await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
    await page.screenshot({path:path.join(output,`dashboard-analytics-${width}.png`),fullPage:true});
  }
  await page.evaluate(()=>setThemePreference('dark'));
  await page.locator('#dashboardExitReasons').screenshot({path:path.join(output,'dashboard-exit-reasons-dark.png'),style:'body > header { opacity:0; }'});
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:path.join(output,'dashboard-analytics-dark.png'),fullPage:true});
  assert.equal(await page.locator('.dash-movement-entry').first().evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(34, 197, 94)');
  assert.equal(await page.evaluate(()=>JSON.stringify(state)===window.originalState),true);
  await page.locator('#dashboardAnalyticsFrom').fill('2026-11-03');await page.locator('#dashboardAnalyticsFrom').dispatchEvent('change');
  assert.match(await page.locator('#dashboardAnalytics [role="alert"]').textContent(),/Confirma as datas/);
  await page.locator('#dashboardAnalyticsFrom').fill('2026-11-01');await page.locator('#dashboardAnalyticsFrom').dispatchEvent('change');
  assert.equal(await metric('entries'),'0');
  console.log(JSON.stringify({largeDashboard:true,onlyEntriesAndExits:true,commissionsRemoved:true,transfersNotCounted:true,drilldown:true,previousPeriod:true,mobile320:true,mobile390:true,darkTheme:true,readOnly:true}));
};
